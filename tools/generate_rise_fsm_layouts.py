"""Generate compact field layouts for RSZ blocks containing Rise's platform-specific player flag.

Usage: python generate_rise_fsm_layouts.py rszmhrise.json output.java weapon1.motfsm2.43 ...
"""
from collections import defaultdict
import json
from pathlib import Path
import struct
import sys


def layouts(registry, files):
    groups = defaultdict(set)
    for file in files:
        data = file.read_bytes()
        tree, = struct.unpack_from("<Q", data, 16)
        for index in range(11):
            relative, = struct.unpack_from("<Q", data, tree + 16 + index * 8)
            base = tree + relative
            if data[base:base + 4] != b"RSZ\0":
                raise ValueError(f"Invalid RSZ in {file}")
            count, = struct.unpack_from("<I", data, base + 12)
            table, = struct.unpack_from("<Q", data, base + 24)
            types = set(struct.iter_unpack("<II", data[base + table:base + table + count * 8]))
            if (839600709, 0x1e8c1a7b) not in types:
                continue
            for type_id, crc in types - {(0, 0)}:
                row = registry[f"{type_id:x}"]
                if int(row["crc"], 16) != crc:
                    raise ValueError(row["name"])
                ops = []
                for field in row["fields"]:
                    if field["type"] in ("String", "Resource") and not field["array"]:
                        op = "s"
                    elif field["array"] and (field["align"], field["size"]) == (4, 4):
                        op = "a"
                    elif not field["array"]:
                        op = {(1, 1): "b", (2, 2): "h", (4, 4): "i", (4, 8): "d",
                              (16, 16): "v"}[field["align"], field["size"]]
                    else:
                        raise ValueError(field)
                    ops.append(op)
                groups["".join(ops)].add(f"{type_id:08x}{crc:08x}")
    return groups


if __name__ == "__main__":
    registry, output, *paths = map(Path, sys.argv[1:])
    groups = layouts(json.loads(registry.read_text(encoding="utf8")), paths)
    lines = ["package io.github.iamwilmar.mhriseport;", "", "// Generated by tools/generate_rise_fsm_layouts.py.",
             "final class RiseFsmLayouts {", "    static void fill(java.util.Map<Long,String> layouts) {"]
    for ops, ids in sorted(groups.items()):
        ordered = sorted(ids)
        for start in range(0, len(ids), 5):
            joined = " ".join(ordered[start:start + 5])
            lines.append(f'        add(layouts, "{ops}", "{joined}");')
    lines.extend(["    }", "    private static void add(java.util.Map<Long,String> layouts, String ops, String keys) {",
                  '        for (String key : keys.split(" ")) layouts.put(Long.parseUnsignedLong(key, 16), ops);',
                  "    }", "}"])
    output.write_text("\n".join(lines) + "\n", encoding="utf8")
